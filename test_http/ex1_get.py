# ============================================================
# 演習1：GETの基本
# ============================================================
# 【目標】URLパラメータを受け取ってブラウザに表示する
# 【確認】python ex1_get.py を起動して以下を試す
#   http://127.0.0.1:5001/
#   http://127.0.0.1:5001/hello?name=太郎
#   http://127.0.0.1:5001/hello?name=太郎&age=20
# ============================================================

from flask import Flask, request   # ①GETパラメータを受け取るために必要なものを import

app = Flask(__name__)


# ── 問題1 ──────────────────────────────────────
# 「/」にアクセスしたとき「トップページです」と表示する
# デコレータのパスを埋めてください

@app.route("/")
def index():
    return "トップページです"


# ── 問題2 ──────────────────────────────────────
# /hello?name=太郎&age=20 のURLパラメータを受け取る
# request.args を使ってパラメータを取得してください

@app.route("/hello")
def hello():
    name = request.args.get("name", "こげまめ")   # ④ どこからパラメータを取る？
    age  = request.args.get("age", "20")  # ⑤ getの書き方

    return f"<h1>こんにちは、{name}さん！年齢: {age}</h1>"


if __name__ == "__main__":
    app.run(debug=True, port=5001)
